<?php

return [

    /*
    |--------------------------------------------------------------------------
    | Secret Key
    |--------------------------------------------------------------------------
    */

    'secret_key' =>
        env(
            'TURNSTILE_SECRET_KEY'
        ),


    /*
    |--------------------------------------------------------------------------
    | Hostnames permitidos
    |--------------------------------------------------------------------------
    */

    'hostnames' =>
        array_filter(
            array_map(
                'trim',
                explode(
                    ',',
                    env(
                        'TURNSTILE_HOSTNAMES',
                        ''
                    )
                )
            )
        ),


    /*
    |--------------------------------------------------------------------------
    | Acción esperada
    |--------------------------------------------------------------------------
    */

    'action' =>
        env(
            'TURNSTILE_ACTION',
            'contacto'
        ),

];
